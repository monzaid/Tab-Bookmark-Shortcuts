/**
 * Generate the single source of truth for protected-URL prefixes (B14 / T15).
 *
 * Before this script the prefix list existed twice, with different ordering:
 *   - src/shared/url-utils.ts    (PROTECTED_PREFIXES)
 *   - src/content/index.ts       (PROTECTED_PREFIXES, inline copy)
 * Any future add/remove in one place would silently diverge, so the content
 * script could disagree with the worker about which pages are protected.
 *
 * Both consumers now import the generated module, and this file is the only
 * place the list is authored. The generated module is a plain TS constant —
 * the content script stays self-contained because Vite bundles the import.
 *
 * Usage: node scripts/gen-protected-prefixes.mjs
 */
import { writeFileSync, readFileSync, existsSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, '..');

/**
 * Two artifacts are emitted from the SAME canonical list below:
 *
 *  - `src/shared/protected-prefixes.generated.ts` — worker side. Imported by
 *    `url-utils.ts`; also imported by other bundles, so Rollup may factor it
 *    into a shared chunk (harmless for the worker).
 *
 *  - `src/content/protected-prefixes.inline.generated.ts` — content side. It
 *    exists so the content script has its OWN module instance: MV3 content
 *    scripts are classic scripts and cannot contain `import` statements, so
 *    sharing the worker's module would emit a chunk import and break injection
 *    at document_start. A content-only module is inlined by Rollup.
 */
const sharedOutPath = resolve(rootDir, 'src', 'shared', 'protected-prefixes.generated.ts');
const contentOutPath = resolve(rootDir, 'src', 'content', 'protected-prefixes.inline.generated.ts');

/**
 * CANONICAL LIST — the single authoring source for protected prefixes.
 * Do not copy this list anywhere else; edit it here and regenerate.
 */
const PROTECTED_PREFIXES = [
  'chrome://',
  'chrome-extension://',
  'edge://',
  'about:',
  'moz-extension://',
  'brave://',
  'opera://',
  'vivaldi://',
];

const banner = `/**
 * AUTO-GENERATED by scripts/gen-protected-prefixes.mjs — DO NOT EDIT BY HAND.
 *
 * Regenerate with: npm run gen:prefixes
 *
 * This is the single source of truth for protected-URL prefixes, consumed by
 * both src/shared/url-utils.ts (worker side) and src/content/index.ts
 * (content script side), so the two can never drift apart.
 */`;

function emit(outPath, header) {
  const contents = `${header}

export const PROTECTED_URL_PREFIXES: readonly string[] = [
${PROTECTED_PREFIXES.map((p) => `  '${p}',`).join('\n')}
];
`;

  const outDir = dirname(outPath);
  if (!existsSync(outDir)) {
    mkdirSync(outDir, { recursive: true });
  }

  const previous = existsSync(outPath) ? readFileSync(outPath, 'utf-8') : null;
  if (previous === contents) {
    console.log(`Protected prefixes unchanged: ${outPath}`);
  } else {
    writeFileSync(outPath, contents, 'utf-8');
    console.log(`Protected prefixes written: ${outPath} (${PROTECTED_PREFIXES.length} entries)`);
  }
}

emit(sharedOutPath, banner);
emit(
  contentOutPath,
  `/**
 * AUTO-GENERATED by scripts/gen-protected-prefixes.mjs — DO NOT EDIT BY HAND.
 *
 * Regenerate with: npm run gen:prefixes
 *
 * CONTENT-SCRIPT VARIANT. Deliberately a separate module instance so Rollup
 * inlines the constant into content.js rather than emitting a shared-chunk
 * import (MV3 content scripts are classic scripts and reject \`import\`).
 * The list itself is authored once, inside the generator.
 */`,
);